val LANGS = listOf("en" to "English", "ko" to "한국어", "es" to "Español", "ja" to "日本語", "de" to "Deutsch")

fun tr(s: String): String {
    textOverride(s, L.lang).let { if (it.isNotEmpty()) return it }
    return when (L.lang) {
        "ko" -> KO[s] ?: s
        "es" -> ES[s] ?: s
        "ja" -> JA[s] ?: s
        "de" -> DE[s] ?: s
        else -> s
    }
}

